/** The pinned router for this provider on this chain, lower-cased, or null. */
export function pinnedRouterFor(
  provider: string | undefined,
  chainId: number | string,
): string | null {
  if (!provider) return null;
  const table = BY_PROVIDER[provider];
  const address = table?.[Number(chainId)];
  return address ? address.toLowerCase() : null;
}
